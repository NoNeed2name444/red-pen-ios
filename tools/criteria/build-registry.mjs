#!/usr/bin/env node
// Builds server/criteria/registry.js, the reviewed rules the vignette checker
// may use (server/vignette-proof.js), from the rule files in
// server/criteria/rules, the source registry (sources.json) and the pinned
// snapshots. A rule enters only when server/criteria/review.js passes it
// (two transcriptions agree, every quote word for word in its pinned source,
// the source's worked examples pass, a licence that allows commercial use);
// a rule that fails is listed under `pending` with its reason. Quoted lexicon
// entries (server/lexicon.js) go through the same review.
//
//   node tools/criteria/build-registry.mjs           write registry.js
//   node tools/criteria/build-registry.mjs --check   exit 1 if it is not current
//
// Deterministic: no clock, no network. The Worker imports the generated
// module, so it needs no JSON import and no file reads.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'server', 'criteria');
const out = join(dir, 'registry.js');

const { reviewRule, reviewLexicon } = await import(join(dir, 'review.js'));
const { quotedEntries } = await import(join(root, 'server', 'lexicon.js'));

/// The registry, built from what is on disk: {text, admitted, pending}.
export function build() {
  const reg = JSON.parse(readFileSync(join(dir, 'sources.json'), 'utf8'));
  const sources = {};
  const snapshots = {};
  for (const s of reg.sources) {
    if (sources[s.id]) throw new Error(`source ${s.id} twice`);
    sources[s.id] = s;
    if (s.snapshot?.file) snapshots[s.id] = { text: readFileSync(join(dir, s.snapshot.file), 'utf8') };
  }
  const ctx = { sources, snapshots };
  const rules = [];
  const pending = [];
  const files = readdirSync(join(dir, 'rules')).filter(f => f.endsWith('.json')).sort();
  const seen = new Set();
  for (const f of files) {
    const rule = JSON.parse(readFileSync(join(dir, 'rules', f), 'utf8'));
    if (`${rule.id}.json` !== f) throw new Error(`${f}: its id is ${rule.id}`);
    if (seen.has(rule.id)) throw new Error(`rule ${rule.id} twice`);
    seen.add(rule.id);
    const r = reviewRule(rule, ctx);
    if (r.ok) rules.push({ ...rule, hash: r.hash });
    else pending.push({ id: rule.id, why: r.why, detail: r.detail });
  }
  const lexicon = [];
  for (const e of quotedEntries()) {
    const r = reviewLexicon(e, ctx);
    if (r.ok) lexicon.push({ id: e.id, slot: e.slot, form: e.form, hash: r.hash });
    else pending.push({ id: e.id, why: r.why, detail: r.detail });
  }
  // what the checker and the app show of a source: never the snapshot text
  const shown = Object.fromEntries(Object.entries(sources).map(([id, s]) => [id, {
    id, title: s.title, publisher: s.publisher, url: s.url, type: s.type, date: s.date, edition: s.edition,
    status: s.status, licence: s.licence, snapshot: s.snapshot ? { sha256: s.snapshot.sha256, fetchedAt: s.snapshot.fetchedAt } : null,
  }]));
  const registry = { version: 1, sources: shown, rules, lexicon, pending };
  const text = '// Generated by tools/criteria/build-registry.mjs from server/criteria/rules,\n'
    + '// sources.json and the pinned snapshots. Do not edit: change a rule file and\n'
    + '// rebuild (a test fails while this is not current).\n'
    + `export default ${JSON.stringify(registry, null, 1)};\n`;
  return { text, rules, pending, lexicon };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { text, rules, pending, lexicon } = build();
  const now = (() => { try { return readFileSync(out, 'utf8'); } catch { return ''; } })();
  for (const r of rules) console.log(`admitted  ${r.id}  ${r.hash.slice(0, 12)}`);
  for (const e of lexicon) console.log(`admitted  lexicon ${e.id}  ${e.hash.slice(0, 12)}`);
  for (const p of pending) console.log(`pending   ${p.id}  ${p.why}: ${p.detail}`);
  if (process.argv.includes('--check')) {
    if (now !== text) {
      console.error('server/criteria/registry.js is not current: run node tools/criteria/build-registry.mjs');
      process.exit(1);
    }
    console.log('registry.js is current');
  } else if (now !== text) {
    writeFileSync(out, text);
    console.log('wrote server/criteria/registry.js');
  } else console.log('registry.js unchanged');
}
